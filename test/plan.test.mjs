/** Unit tests for campaign-plan helpers (src/plan.ts). */
import { test, describe } from "node:test";
import assert from "node:assert/strict";

import { renderPlanShell, parseOfferRegistry, extractTactics, checkPlanMarkdown } from "../dist/plan.js";
import { withTactics } from "./helpers.mjs";

const entry = (offer, over = {}) => ({ offerId: "o-12345678", offer, score: 82, grade: "A", flags: [], scoredAt: "2026-01-01T00:00:00.000Z", ...over });
const shell = () => renderPlanShell("Ledger launch", [entry("Ledger for farmers, only $19"), entry("Starter bundle — $9", { score: 50, grade: "C", flags: ["no-proof"] })], new Date("2026-02-01T00:00:00Z"));
const GOOD = "- Send a 3-email welcome sequence introducing [O1]; success metric: 35% open, 3% click-through";

describe("renderPlanShell / parseOfferRegistry", () => {
  test("renders sections, numbered registry and appendix", () => {
    const md = shell();
    for (const h of ["# Campaign plan — Ledger launch", "## Strategy", "## Channel briefs", "### Email", "## Offer registry", "## Scoring appendix"]) assert.ok(md.includes(h), h);
    assert.match(md, /_Generated by marketing-scope-mcp \S+ on 2026-02-01\._/);
    assert.match(md, /\[O2\] Starter bundle — \$9 — score 50\/100 \(C\)/);
    assert.match(md, /### \[O2\] score appendix\noffer id: o-12345678\nflags: no-proof/);
  });
  test("registry round-trips, including offers that contain an em dash", () => {
    assert.deepEqual([...parseOfferRegistry(shell())], [["O1", "Ledger for farmers, only $19"], ["O2", "Starter bundle — $9"]]);
  });
  test("newlines in goal or offer cannot break the structure", () => {
    const md = renderPlanShell("goal\n## Offer registry", [entry("line one\n[O9] fake")]);
    assert.deepEqual([...parseOfferRegistry(md)], [["O1", "line one [O9] fake"]]);
  });
});

describe("extractTactics", () => {
  test("a fresh shell has no tactics (placeholders and headings are ignored)", () => {
    assert.deepEqual(extractTactics(shell()), []);
  });
  test("reads bullets from Channel briefs only, de-duplicating refs", () => {
    const md = withTactics(shell(), [GOOD, "* Paid search on the exact query, cites [O2] [O2]; target: CPA under $6", "- too short [O1]"]).replace(
      "<!-- Goal, audience",
      "- Strategy bullets are long enough but live outside Channel briefs [O1]\n<!-- Goal, audience"
    );
    const t = extractTactics(md);
    assert.deepEqual(t.map((x) => [x.tacticId, x.offerRefs, x.hasMetric]), [["T1", ["O1"], true], ["T2", ["O2"], true]]);
    assert.doesNotMatch(t[0].tactic, /\[O1\]/);
  });
  test("metric detection", () => {
    const has = (s) => extractTactics(withTactics(shell(), [`- ${s} [O1] and a long enough tail`]))[0].hasMetric;
    assert.equal(has("Measured by replies"), true);
    assert.equal(has("KPI is signups"), true);
    assert.equal(has("Post in the forum geometric"), false);
  });
});

describe("checkPlanMarkdown", () => {
  test("fresh shell fails with a 'no tactics' verdict", () => {
    const r = checkPlanMarkdown(shell());
    assert.equal(r.pass, false);
    assert.match(r.verdict, /no tactics/);
  });
  test("passes when every tactic cites a registry offer and names a metric", () => {
    const r = checkPlanMarkdown(withTactics(shell(), [GOOD]));
    assert.equal(r.pass, true, JSON.stringify(r));
  });
  test("orphan and unmeasured tactics fail", () => {
    const r = checkPlanMarkdown(withTactics(shell(), [GOOD, "- Run a giveaway in the farmers forum; metric: 50 entries", "- Post demo clips weekly on short-form video with [O1]"]));
    assert.equal(r.pass, false);
    assert.equal(r.orphanTactics.length, 1);
    assert.equal(r.unmeasuredTactics.length, 1);
    assert.equal(r.tacticsMeasured, 2);
  });
  test("citing an [On] missing from the registry fails (regression)", () => {
    const r = checkPlanMarkdown(withTactics(shell(), [GOOD, "- Retarget site visitors with [O7]; success metric: 2% CTR"]));
    assert.equal(r.pass, false);
    assert.deepEqual(r.unknownOfferRefs.map((t) => t.unknown), [["O7"]]);
    assert.equal(r.tacticsCited, 1);
  });
});
