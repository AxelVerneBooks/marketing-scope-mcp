/**
 * marketing-scope-mcp — campaign-plan model and tactic checking.
 *
 * Pure functions only (no filesystem) so they can be unit-tested directly; the
 * tool handlers in server.ts own I/O.
 */

import { version } from "./version.js";

export interface RegistryEntry {
  offerId: string;
  offer: string;
  score: number;
  grade: string;
  flags: string[];
  scoredAt: string;
}

export interface Tactic {
  tactic: string;
  tacticId: string;
  /** Offer citations found on the tactic line, e.g. ["O1"] */
  offerRefs: string[];
  hasMetric: boolean;
}

export interface CheckResult {
  pass: boolean;
  tacticsFound: number;
  tacticsCited: number;
  tacticsMeasured: number;
  orphanTactics: Tactic[];
  unmeasuredTactics: Tactic[];
  /** Tactics citing an [On] that is not in the plan's offer registry */
  unknownOfferRefs: Array<Tactic & { unknown: string[] }>;
  verdict: string;
}

/** Text of a "## Heading" section, up to the next "## " heading. */
function section(markdown: string, heading: RegExp): string[] | null {
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => heading.test(l.trim()));
  if (start < 0) return null;
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => /^##\s/.test(l.trim()));
  return end < 0 ? rest : rest.slice(0, end);
}

/** Map of offer citation id ("O1") -> offer text, read from the plan's "## Offer registry" section. */
export function parseOfferRegistry(markdown: string): Map<string, string> {
  const registry = new Map<string, string>();
  for (const line of section(markdown, /^## Offer registry/i) ?? []) {
    const m = line.trim().match(/^\[O(\d+)\]\s+(.+?)(?:\s+—\s+score\s+\d+\/100.*)?$/);
    if (m) registry.set(`O${m[1]}`, m[2]);
  }
  return registry;
}

/** Extract tactic bullets from a plan's "## Channel briefs" section. */
export function extractTactics(markdown: string): Tactic[] {
  const tactics: Tactic[] = [];
  let inFence = false;
  for (const line of section(markdown, /^## Channel briefs/i) ?? []) {
    const trimmed = line.trim();
    if (/^(```|~~~)/.test(trimmed)) {
      inFence = !inFence;
      continue;
    }
    // ### channel sub-headings are structure, not tactics; tactics are bullets
    if (inFence || !/^[-*+]\s/.test(trimmed)) continue;
    const body = trimmed.slice(2).trim();
    if (body.startsWith("<!--") || body.startsWith("_") || body.length < 30) continue;
    const refs = [...new Set([...body.matchAll(/\[O(\d+)\]/g)].map((m) => `O${m[1]}`))];
    tactics.push({
      tactic: body.replace(/\s*\[O\d+\]/g, "").trim(),
      tacticId: `T${tactics.length + 1}`,
      offerRefs: refs,
      hasMetric: /\bmetrics?\b|measured by|\btarget:|\bkpi\b/i.test(body),
    });
  }
  return tactics;
}

/** Every tactic must cite an [On] from the plan's own registry and name a success metric. */
export function checkPlanMarkdown(markdown: string): CheckResult {
  const tactics = extractTactics(markdown);
  const registry = parseOfferRegistry(markdown);
  const orphanTactics = tactics.filter((t) => t.offerRefs.length === 0);
  const unmeasuredTactics = tactics.filter((t) => !t.hasMetric);
  const unknownOfferRefs = tactics
    .map((t) => ({ ...t, unknown: t.offerRefs.filter((id) => !registry.has(id)) }))
    .filter((t) => t.unknown.length > 0);
  const pass = tactics.length > 0 && orphanTactics.length === 0 && unmeasuredTactics.length === 0 && unknownOfferRefs.length === 0;
  let verdict: string;
  if (pass) verdict = "PASS — every tactic cites a scored offer and names a metric";
  else if (tactics.length === 0) verdict = "FAIL — no tactics written yet; fill the channel briefs with one tactic per bullet";
  else verdict = "FAIL — fix orphan/unmeasured tactics and citations to offers missing from the registry before spending money";
  return {
    pass,
    tacticsFound: tactics.length,
    tacticsCited: tactics.filter((t) => t.offerRefs.length > 0 && t.offerRefs.every((id) => registry.has(id))).length,
    tacticsMeasured: tactics.length - unmeasuredTactics.length,
    orphanTactics,
    unmeasuredTactics,
    unknownOfferRefs,
    verdict,
  };
}

export function renderPlanShell(goal: string, offers: RegistryEntry[], now = new Date()): string {
  const lines: string[] = [];
  lines.push(`# Campaign plan — ${goal.replace(/\s+/g, " ").trim()}`);
  lines.push("");
  lines.push(`_Generated by marketing-scope-mcp ${version} on ${now.toISOString().slice(0, 10)}._`);
  lines.push("_Every tactic below must cite at least one offer from the registry ([O1], [O2] ...) AND name a success metric. Uncited tactics fail `check_plan`._");
  lines.push("");
  lines.push("## Strategy");
  lines.push("");
  lines.push("<!-- Goal, audience, voice, and timing constraints. Bullets or short paragraphs. -->");
  lines.push("");
  lines.push("## Channel briefs");
  lines.push("");
  lines.push("### Email");
  lines.push("- <!-- Example: - Send 3-email welcome sequence to list introducing [O1]; success metric: 35% open, 3% click-through -->");
  lines.push("");
  lines.push("### Paid");
  lines.push("- <!-- One-payoff tactic per line, each citing an offer [On] and a metric -->");
  lines.push("");
  lines.push("### Social");
  lines.push("- <!-- Short-form hooks, demos, receipts. Each tactic: [On] + metric -->");
  lines.push("");
  lines.push("### SEO / content");
  lines.push("- <!-- Pages and posts targeting named queries. Each tactic: [On] + metric -->");
  lines.push("");
  lines.push("### Community");
  lines.push("- <!-- Where the audience already talks. Each tactic: [On] + metric -->");
  lines.push("");
  lines.push("## Offer registry");
  lines.push("");
  offers.forEach((o, i) => {
    lines.push(`[O${i + 1}] ${o.offer.replace(/\s+/g, " ")} — score ${o.score}/100 (${o.grade})`);
  });
  lines.push("");
  lines.push("## Scoring appendix");
  lines.push("");
  offers.forEach((o, i) => {
    lines.push(`### [O${i + 1}] score appendix`);
    lines.push(`offer id: ${o.offerId}`);
    lines.push(`flags: ${o.flags.length ? o.flags.join(", ") : "none"}`);
    lines.push("");
  });
  return lines.join("\n");
}
