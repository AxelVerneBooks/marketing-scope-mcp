// Factory (not a singleton): the Streamable HTTP transport is stateless and
// requires a fresh server + transport pair per request. Shared in-memory
// registries (scoreRegistry, plans) live at module scope, so every instance
// sees the same scores/plans.
function buildServer(): McpServer {
  const server: McpServer = new McpServer(
    { name: "marketing-scope-mcp", version },
    {
      instructions:
        "Marketing campaign workflow. Use plan_campaign first, then score_offer for each candidate offer, then build_plan, then check_plan BEFORE spending money. Never send traffic at an unscored offer.",
    }
  );

  installFriendlyValidation(server);

  /* --- tool 1: plan_campaign ---------------------------------------- */

  server.registerTool(
    "plan_campaign",
    {
      title: "Plan a campaign",
      description:
        "Turn a campaign objective into a pre-spend plan: offer targets, channel targets, anti-targets (budget black holes), and kill criteria. Purpose: decompose a marketing goal into scoreable tactics BEFORE any spend. Use this before score_offer on any new product/launch; re-plan only when kill criteria trigger. Sibling distinction: score_offer grades ONE offer statement; this plans the whole campaign strategy.",
      inputSchema: planCampaignInput,
      annotations: { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false },
    },
    async ({ objective, audience_hints }) => {
      const hints = audience_hints?.length ? audience_hints : ["existing email list", "relevant subreddit/forum", "niche Facebook/LinkedIn groups"];
      const plan = {
        objective,
        generatedAt: new Date().toISOString(),
        offerTargets: [
          { what: "One primary offer statement (the exact sentence a prospect would see)", why: "everything downstream cites it; vague offers cannot be scored honestly" },
          { what: "One fallback offer or angle (bundle, guarantee framing, starter tier)", why: "lets A/B reality check without re-planning the whole campaign" },
        ],
        channelTargets: [
          { what: hints[0], why: "warmest channel; lowest cost per impression in the scorer's eyes" },
          { what: hints[1] ?? "one named community where the audience already asks for this", why: "proof-of-demand before paid spend" },
          { what: "one SEO/content page answering a query the audience already types", why: "compounding; survives a failed paid push" },
        ],
        antiTargets: [
          "broad/top-of-funnel ads before the offer scores >= B",
          "buying reach for an unmeasured tactic (no metric = no channel)",
          "rebranding or redesigning mid-launch",
        ],
        killCriteria: [
          "Every scored offer below 45/100 -> STOP; rework the offer before spending anything on traffic",
          "One-week no-traction on all channels with an A/B offer live -> re-plan rather than raise spend",
          "Cost per acquisition exceeds 1/3 of first-order profit for 7+ days -> kill the channel",
        ],
      };
      return {
        content: [{ type: "text" as const, text: JSON.stringify(plan, null, 2) }],
      };
    }
  );

  /* --- tool 2: score_offer ------------------------------------------ */

  let registryCounter = 0;
  server.registerTool(
    "score_offer",
    {
      title: "Score an offer",
      description:
        "Score one offer statement (the exact sentence a prospect would read) on an explainable 0–100 offer-strength scale: clarity 20 / audience specificity 24 / differentiation 20 / proof & risk reversal 20 / call to action 16. Grades: A >= 80, B >= 65, C >= 45, D < 45. Every dimension comes back WITH its evidence, so the number is auditable rather than a vibe. Side effect: the score is cached in an in-memory registry keyed by the exact offer text (lost on restart; re-score before finalizing a plan). Do NOT use it as a general copy critique — it grades offer statements, not landing pages. Sibling distinction: plan_campaign plans the strategy; this grades one sentence; build_plan consumes the scores.",
      inputSchema: scoreOfferInput,
      annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: true, openWorldHint: false },
    },
    async ({ offer, audience }) => {
      const scored = scoreOffer({ offer, audience });
      registryCounter += 1;
      scored.offerId = `o-${randomUUID().slice(0, 4).toLowerCase()}`;
      scoreRegistry.set(offer.trim(), scored);
      scoreRegistry.set(scored.offerId, scored);
      return {
        content: [{ type: "text" as const, text: JSON.stringify(scored, null, 2) }],
      };
    }
  );

  /* --- tool 3: build_plan ------------------------------------------- */

  server.registerTool(
    "build_plan",
    {
      title: "Build campaign-plan shell",
      description:
        "Build a campaign-plan shell from already-scored offers: strategy stubs, channel briefs, numbered offer registry, scoring appendix. Writes a markdown file under data/campaigns/ and returns the plan id plus the shell text. Do NOT call it before each offer has a score_offer — unscored offer texts are rejected with an error naming them. Sibling distinction: this creates the shell; check_plan later validates everything written against it.",
      inputSchema: buildPlanInput,
      annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false },
    },
    async ({ goal, offers }) => {
      const entries: RegistryEntry[] = [];
      const missing: string[] = [];
      for (const offer of offers) {
        const s = scoreRegistry.get(offer.trim());
        if (!s) {
          missing.push(offer);
          continue;
        }
        entries.push({ offerId: s.offerId, offer: s.offer, score: s.score, grade: s.grade, flags: s.flags, scoredAt: s.scoredAt });
      }
      if (missing.length) {
        return toolError(
          `These offers were never scored — run score_offer on each one first (offers must match the scored text exactly, and scores are lost when the server restarts):\n${missing.map((m) => `- ${m}`).join("\n")}`
        );
      }
      const id = randomUUID().slice(0, 8);
      const markdown = renderPlanShell(goal, entries);
      const planPath = pathResolve(DATA_DIR, "campaigns", `campaign-${id}.md`);
      try {
        mkdirSync(pathResolve(DATA_DIR, "campaigns"), { recursive: true });
        writeFileSync(planPath, markdown, "utf8");
      } catch (err) {
        return toolError(
          `Could not save the campaign plan to ${planPath}: ${describeFsError(err)}. ` +
            "Set MARKETING_SCOPE_DATA_DIR to a writable directory and retry."
        );
      }
      const plan: StoredPlan = {
        id,
        goal,
        createdAt: new Date().toISOString(),
        offers: entries,
        markdown,
      };
      plans.set(id, plan);
      const registryLine = entries.map((e, i) => `[O${i + 1}] ${e.offer} (${e.score}/100, ${e.grade})`).join("\n");
      return {
        content: [
          {
            type: "text" as const,
            text: `Campaign shell ${id} saved to ${planPath}\n\n---\n${markdown}\n---\n\nOffer registry:\n${registryLine}\nCite these [On] numbers from every tactic and give each a success metric, then run check_plan.`,
          },
        ],
      };
    }
  );

  /* --- tool 4: check_plan ------------------------------------------- */

  server.registerTool(
    "check_plan",
    {
      title: "Check plan tactic coverage",
      description:
        "Verify every substantive campaign tactic (a) cites at least one scored offer from the registry and (b) names a success metric. Violations are returned as an error list — never a silent pass. Read-only tool: inspects the registry and the plan file but writes nothing. Use it after every build_plan and again after any manual edit; do NOT use it on arbitrary markdown that never went through build_plan without first scoring its offers. Sibling distinction: build_plan creates the registry-backed shell; check_plan validates whatever is on disk against that registry.",
      inputSchema: checkPlanInput,
      annotations: { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false },
    },
    async ({ plan_id, plan_path }) => {
      let markdown: string;
      let label: string;
      if (plan_path) {
        const p = pathResolve(plan_path);
        if (!existsSync(p)) {
          return toolError(`Plan file not found: ${p}. Pass the path build_plan printed ("saved to ..."), or use plan_id instead.`);
        }
        if (!statSync(p).isFile()) {
          return toolError(`plan_path must point to a campaign markdown file, but ${p} is a directory. Example: data/campaigns/campaign-3f9a2c1b.md`);
        }
        try {
          markdown = readFileSync(p, "utf8");
        } catch (err) {
          return toolError(`Could not read plan file ${p}: ${describeFsError(err)}.`);
        }
        label = p;
      } else if (plan_id) {
        const stored = plans.get(plan_id);
        if (!stored) {
          const known = [...plans.keys()];
          return toolError(
            `No plan with id "${plan_id}" in this server session. ` +
              (known.length ? `Known plan ids: ${known.join(", ")}. ` : "No plans have been built yet — run build_plan first. ") +
              "Plans built before a server restart are only reachable via plan_path."
          );
        }
        markdown = stored.markdown;
        label = plan_id;
      } else {
        return toolError(CHECK_PLAN_MISSING_TARGET);
      }

      const tactics = extractTactics(markdown);
      const orphan = tactics.filter((t) => t.offerRefs.length === 0);
      const unmeasured = tactics.filter((t) => !t.hasMetric);
      const ok = orphan.length === 0 && unmeasured.length === 0 && tactics.length > 0;

      return {
        content: [
          {
            type: "text" as const,
            text: JSON.stringify(
              {
                plan: label,
                pass: ok,
                tacticsFound: tactics.length,
                tacticsCited: tactics.length - orphan.length,
                tacticsMeasured: tactics.length - unmeasured.length,
                orphanTactics: orphan.length ? orphan : "none",
                unmeasuredTactics: unmeasured.length ? unmeasured : "none",
                verdict: ok
                  ? "PASS — every tactic cites a scored offer and names a metric"
                  : tactics.length === 0
                    ? "FAIL — no tactics written yet; fill the channel briefs with one tactic per bullet"
                    : "FAIL — fix orphan/unmeasured tactics above before spending money",
              },
              null,
              2
            ),
          },
        ],
      };
    }
  );

  return server;
}

// stdio keeps one long-lived server for the process lifetime.
const server: McpServer = buildServer();

/* ------------------------------------------------------------------ */
/* transports                                                          */
/* ------------------------------------------------------------------ */

async function runStdio(): Promise<void> {
  const transport = new StdioServerTransport();
  await server.connect(transport);
  // stdio keeps the process alive until the client closes the pipe
}

function runHttp(port: number): void {
  // Stateless Streamable HTTP: the SDK requires a fresh transport per request
  // (a reused stateless transport throws "cannot be reused across requests"
  // from the second request on, which surfaced as silent 500s in the sibling
  // project). Mirror the SDK's official stateless example: new server + new
  // transport per request, both closed when the response ends. Module-scope
  // registries keep state.
  const httpServer = createHttpServer((req, res) => {
    void (async () => {
      try {
        const requestServer = buildServer();
        const transport = new StreamableHTTPServerTransport({ sessionIdGenerator: undefined });
        res.on("close", () => {
          void transport.close();
          if (requestServer) {
            void requestServer.close();
          }
        });
        await requestServer.connect(transport);
        await transport.handleRequest(req, res);
        // Note: closing the pair here (after a completed request) would race
        // clients that keep SSE streams open; the "close" listener owns teardown.
      } catch (err) {
        if (!res.headersSent) {
          res.statusCode = 500;
          res.setHeader("content-type", "application/json");
        }
        const payload = JSON.stringify({ jsonrpc: "2.0", error: { code: -32700, message: (err as Error).message } });
        if (!res.writableEnded) {
          res.end(payload);
        } else {
          res.destroy();
        }
      }
    })();
  });
  httpServer.listen(port, () => {
    const addr = httpServer.address();
    const bound = typeof addr === "object" && addr ? `${addr.address}:${addr.port}` : String(port);
    console.error(`marketing-scope-mcp ${version} listening (Streamable HTTP) on http://${bound}/mcp`);
  });
}

/* --- entry -------------------------------------------------------- */

const args = process.argv.slice(2);
if (args.includes("--http")) {
  const portIdx = args.indexOf("--port");
  const port = portIdx >= 0 ? Number(args[portIdx + 1]) || 3002 : Number(process.env.PORT) || 3002;
  runHttp(port);
} else {
  runStdio().catch((err) => {
    console.error("stdio transport failed:", err);
    process.exit(1);
  });
}
