/**
 * marketing-scope-mcp — MCP server (v0.1.0)
 *
 * Marketing campaign workflow: plan a campaign with kill criteria, score
 * candidate offers explainably (0–100), assemble a campaign-plan shell with an
 * offer registry, then verify every tactic cites a scored offer AND names a
 * success metric before any money gets spent.
 *
 * Transports:
 *   - stdio (default):  `node dist/index.js`
 *   - Streamable HTTP:  `node dist/index.js --http --port 3002`
 *
 * Tools:
 *   plan_campaign(objective)              -> channel/offer plan with kill criteria
 *   score_offer(offer, audience?)         -> explainable 0–100 offer-strength score
 *   build_plan(goal, offers[])            -> campaign-plan shell (markdown); unscored offers rejected
 *   check_plan(plan_id|plan_path)         -> every tactic must cite [On] + a success metric
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { resolve as pathResolve } from "node:path";
import { createServer as createHttpServer } from "node:http";

import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { StreamableHTTPServerTransport } from "@modelcontextprotocol/sdk/server/streamableHttp.js";
import { CallToolRequestSchema } from "@modelcontextprotocol/sdk/types.js";
import { scoreOffer, type OfferScore } from "./scoring/offer.js";
import { version } from "./version.js";
import {
  planCampaignInput,
  scoreOfferInput,
  buildPlanInput,
  checkPlanInput,
  CHECK_PLAN_MISSING_TARGET,
  toolInputSchemas,
  validateToolArgs,
  type ToolName,
} from "./validation.js";

const DATA_DIR = pathResolve(process.env.MARKETING_SCOPE_DATA_DIR ?? pathResolve(process.cwd(), "data"));

/* ------------------------------------------------------------------ */
/* campaign model                                                      */
/* ------------------------------------------------------------------ */

interface RegistryEntry {
  offerId: string;
  offer: string;
  score: number;
  grade: string;
  flags: string[];
  scoredAt: string;
}

interface StoredPlan {
  id: string;
  goal: string;
  createdAt: string;
  offers: RegistryEntry[];
  markdown: string;
}

const scoreRegistry = new Map<string, OfferScore>();
const plans = new Map<string, StoredPlan>();

/* ------------------------------------------------------------------ */
/* helpers                                                             */
/* ------------------------------------------------------------------ */

/** A tool result that reports a problem the caller can fix. */
function toolError(text: string) {
  return { isError: true, content: [{ type: "text" as const, text }] };
}

/** Turn a Node fs error into a short, human-readable reason. */
function describeFsError(err: unknown): string {
  const e = err as NodeJS.ErrnoException;
  switch (e?.code) {
    case "EACCES":
    case "EPERM":
      return "permission denied";
    case "ENOENT":
      return "a parent directory does not exist";
    case "ENOTDIR":
      return "part of the path is a file, not a directory";
    case "EISDIR":
      return "the path is a directory, not a file";
    case "ENOSPC":
      return "no space left on device";
    case "EROFS":
      return "the file system is read-only";
    default:
      return e?.message ?? String(err);
  }
}

/** Extract tactic-looking lines from a plan's Channel briefs section. */
function extractTactics(markdown: string): Array<{ tactic: string; tacticId: string; offerRefs: string[]; hasMetric: boolean }> {
  let i = 0;
  const tactics: Array<{ tactic: string; tacticId: string; offerRefs: string[]; hasMetric: boolean }> = [];
  const start = markdown.indexOf("## Channel briefs");
  const end = markdown.indexOf("## Offer registry");
  if (start < 0) return tactics;
  const section = markdown.slice(start, end > 0 ? end : undefined);
  section.split("\n").forEach((line) => {
    const trimmed = line.trim();
    const isHeading = /^#{3}\s/.test(trimmed); // ### Channel sub-headings are structure, not tactics
    if (!trimmed || isHeading || !trimmed.startsWith("- ")) return;
    const body = trimmed.slice(2).trim();
    if (body.startsWith("<!--") || body.startsWith("_") || body.length < 30) return;
    const refs = [...body.matchAll(/\[O(\d+)\]/g)].map((m) => `O${m[1]}`);
    i += 1;
    tactics.push({
      tactic: body.replace(/\[O\d+\]/g, "").trim(),
      tacticId: `T${i}`,
      offerRefs: refs,
      hasMetric: /metric|measured by|target:/i.test(body),
    });
  });
  return tactics;
}

function renderPlanShell(goal: string, offers: RegistryEntry[]): string {
  const lines: string[] = [];
  lines.push(`# Campaign plan — ${goal}`);
  lines.push("");
  lines.push(`_Generated by marketing-scope-mcp ${version} on ${new Date().toISOString().slice(0, 10)}._`);
  lines.push("_Every tactic below must cite at least one offer from the registry ([O1], [O2] ...) AND name a success metric. Uncited tactics fail `check_plan`._");
  lines.push("");
  lines.push("## Strategy");
  lines.push("");
  lines.push("<!-- Goal, audience, voice, and timing constraints. Bullets or short paragraphs. -->");
  lines.push("");
  lines.push("## Channel briefs");
  lines.push("");
  lines.push("### Email");
  lines.push("- <!-- Example: - Send 3-email welcome sequence to list introducing [O1]; success metric: 35% open, 3% click-through -->");
  lines.push("");
  lines.push("### Paid");
  lines.push("- <!-- One-payoff tactic per line, each citing an offer [On] and a metric -->");
  lines.push("");
  lines.push("### Social");
  lines.push("- <!-- Short-form hooks, demos, receipts. Each tactic: [On] + metric -->");
  lines.push("");
  lines.push("### SEO / content");
  lines.push("- <!-- Pages and posts targeting named queries. Each tactic: [On] + metric -->");
  lines.push("");
  lines.push("### Community");
  lines.push("- <!-- Where the audience already talks. Each tactic: [On] + metric -->");
  lines.push("");
  lines.push("## Offer registry");
  lines.push("");
  offers.forEach((o, i) => {
    lines.push(`[O${i + 1}] ${o.offer} — score ${o.score}/100 (${o.grade})`);
  });
  lines.push("");
  lines.push("## Scoring appendix");
  lines.push("");
  offers.forEach((o, i) => {
    lines.push(`### [O${i + 1}] score appendix`);
    o.flags.length ? lines.push(`flags: ${o.flags.join(", ")}`) : lines.push("flags: none");
    lines.push("");
  });
  return lines.join("\n");
}

/**
 * Validate every tools/call against our strict schemas BEFORE the SDK does,
 * so a rejected call returns one readable, actionable list of problems
 * (isError: true) instead of the SDK's generic "MCP error -32602 ..." text.
 * Hooks the public Server.setRequestHandler so it wraps whatever tools/call
 * handler McpServer installs; valid calls pass through untouched.
 */
function installFriendlyValidation(mcp: McpServer): void {
  const low = mcp.server;
  const original = low.setRequestHandler.bind(low);
  low.setRequestHandler = ((schema: unknown, handler: (request: any, extra: any) => unknown) => {
    if (schema !== CallToolRequestSchema) return original(schema as any, handler as any);
    return original(CallToolRequestSchema, async (request, extra) => {
      const name = request.params.name;
      if (Object.prototype.hasOwnProperty.call(toolInputSchemas, name)) {
        const checked = validateToolArgs(name as ToolName, request.params.arguments);
        if (!checked.ok) return toolError(checked.message);
      }
      return (await handler(request, extra)) as any;
    });
  }) as typeof low.setRequestHandler;
}

